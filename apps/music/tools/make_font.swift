// Rasterizes the Music app's type into compact anti-aliased glyphs for
// apps/music/font.rs. Space Grotesk and Inter are SIL OFL 1.1 fonts (see
// apps/music/fonts/); only rendered glyph bitmaps ship in the app.
//
//   swift apps/music/tools/make_font.swift <dir with space_grotesk.ttf, inter.ttf> > apps/music/font.rs
//
// Each glyph is its ink box in 4-bit alpha, coded as a nibble stream in raster
// order: 1..14 is one pixel of that alpha; 0 n is n+1 clear pixels; 15 n is
// n+1 solid pixels. Advances are in quarter pixels. Pair kerning is kept for
// the pairs that occur in each face's strings.
import CoreGraphics
import CoreText
import Foundation

let dir = CommandLine.arguments.count > 1 ? CommandLine.arguments[1] : "."

let titles = ["Glass Orchard", "Neon Koi", "Velvet Static", "Paper Lanterns", "Hyperbloom",
              "Sugar Circuit", "Moth Logic", "Kintsugi", "Afterglow Arcade", "Halcyon Drift"]
let keys = ["E major", "F# minor", "D major", "A major", "C# minor", "G major", "B minor", "E minor",
            "D# minor", "F major"]
// Every string apps/music/process.rs draws in the small face (keep in step).
let ui = ["Rose Music Ensemble", "PLAYING FROM", "ALBUM \u{B7} 10 SONGS \u{B7} 25 MIN", "Glass Orchard",
          "Ready \u{B7} 10 songs to stream", "Offline \u{B7} connect Wi-Fi to stream", "Library is waking up",
          "Connecting to the library", "Paused", "Finished", "Stopped", "Live from the library",
          "Live \u{B7} 4.2 s buffered", "140 BPM \u{B7} ", "BPM"]

struct Spec {
    let name: String, file: String, weight: Double, size: Double, chars: String, strings: [String]
}
let specs = [
    Spec(name: "HERO", file: "space_grotesk.ttf", weight: 700, size: 76, chars: "",
         strings: ["Glass Orchard"]),
    Spec(name: "TITLE", file: "space_grotesk.ttf", weight: 700, size: 54, chars: "",
         strings: titles),
    Spec(name: "ROW", file: "inter.ttf", weight: 600, size: 31, chars: "",
         strings: titles),
    Spec(name: "META", file: "inter.ttf", weight: 500, size: 24, chars: "0123456789:-. ",
         strings: ui + keys),
]

func font(_ spec: Spec) -> CTFont {
    let url = URL(fileURLWithPath: dir).appendingPathComponent(spec.file) as CFURL
    let descs = CTFontManagerCreateFontDescriptorsFromURL(url) as! [CTFontDescriptor]
    let wght = 0x7767_6874
    let desc = CTFontDescriptorCreateCopyWithAttributes(descs[0], [
        kCTFontVariationAttribute: [wght: spec.weight],
    ] as CFDictionary)
    return CTFontCreateWithFontDescriptor(desc, spec.size, nil)
}

func glyphOf(_ f: CTFont, _ c: Character) -> CGGlyph {
    var chars = Array(String(c).utf16)
    var glyphs = [CGGlyph](repeating: 0, count: chars.count)
    CTFontGetGlyphsForCharacters(f, &chars, &glyphs, chars.count)
    return glyphs[0]
}

func lineWidth(_ f: CTFont, _ s: String) -> Double {
    let attr = NSAttributedString(string: s, attributes: [kCTFontAttributeName as NSAttributedString.Key: f])
    let line = CTLineCreateWithAttributedString(attr)
    return CTLineGetTypographicBounds(line, nil, nil, nil)
}

var out = "// Generated by apps/music/tools/make_font.swift. Do not edit.\n"
out += "// Glyphs rendered from Space Grotesk and Inter (SIL Open Font License 1.1, see apps/music/fonts/).\n"
out += "pub struct Glyph { pub off: u16, pub w: u8, pub h: u8, pub x: i8, pub top: i8, pub adv: u8 }\n"
out += "pub struct Font { pub ascent: u8, pub descent: u8, pub map: &'static [u8; 96], pub glyphs: &'static [Glyph], pub data: &'static [u8], pub kern: &'static [(u8, u8, i8)] }\n"
var total = 0

for spec in specs {
    let f = font(spec)
    var set = Set(spec.chars)
    for s in spec.strings { for c in s { set.insert(c) } }
    let chars = set.sorted().filter { ($0.asciiValue ?? 0) >= 32 || $0 == "\u{00B7}" }
    var map = [UInt8](repeating: 255, count: 96)
    var data = [UInt8]()
    var glyphRows = [String]()
    // Tabular figures: every digit takes the widest digit's advance.
    var digitAdv = 0.0
    for d in "0123456789" {
        var g = glyphOf(f, d); var a = CGSize.zero
        CTFontGetAdvancesForGlyphs(f, .horizontal, &g, &a, 1)
        digitAdv = max(digitAdv, Double(a.width))
    }
    for (i, c) in chars.enumerated() {
        let code = c == "\u{00B7}" ? 127 : Int(c.asciiValue!)
        map[code - 32] = UInt8(i)
        var g = glyphOf(f, c)
        var adv = CGSize.zero
        CTFontGetAdvancesForGlyphs(f, .horizontal, &g, &adv, 1)
        var advance = Double(adv.width)
        var shift = 0.0
        if c.isNumber { shift = (digitAdv - advance) / 2; advance = digitAdv }
        let rect = CTFontGetBoundingRectsForGlyphs(f, .horizontal, &g, nil, 1)
        let pad = 2
        let ox = Int(floor(rect.minX)) - pad, oy = Int(floor(rect.minY)) - pad
        let w = max(1, Int(ceil(rect.maxX)) - ox + pad), h = max(1, Int(ceil(rect.maxY)) - oy + pad)
        var pixels = [UInt8](repeating: 0, count: w * h)
        let ctx = CGContext(data: &pixels, width: w, height: h, bitsPerComponent: 8, bytesPerRow: w,
                            space: CGColorSpaceCreateDeviceGray(), bitmapInfo: CGImageAlphaInfo.none.rawValue)!
        ctx.setAllowsFontSmoothing(false)
        ctx.setShouldSmoothFonts(false)
        ctx.setAllowsAntialiasing(true)
        ctx.setShouldAntialias(true)
        ctx.setFillColor(gray: 1, alpha: 1)
        var pos = CGPoint(x: Double(-ox) + shift.rounded(), y: Double(-oy))
        CTFontDrawGlyphs(f, &g, &pos, 1, ctx)
        // pixels row 0 is the top of the image.
        var x0 = w, x1 = -1, y0 = h, y1 = -1
        for y in 0..<h { for x in 0..<w where pixels[y * w + x] > 8 {
            x0 = min(x0, x); x1 = max(x1, x); y0 = min(y0, y); y1 = max(y1, y)
        } }
        let off = data.count
        var gw = 0, gh = 0, bx = 0, top = 0
        if x1 >= 0 {
            gw = x1 - x0 + 1; gh = y1 - y0 + 1
            bx = ox + x0
            top = (h + oy) - y0  // pixels above the baseline to the first ink row
            var nibbles = [UInt8]()
            var run = 0, runV: UInt8 = 0
            func flush() {
                while run > 0 { let n = min(run, 16); nibbles += [runV, UInt8(n - 1)]; run -= n }
            }
            for y in y0...y1 { for x in x0...x1 {
                // A little gamma lift so light-on-dark text keeps its weight.
                let a = pow(Double(pixels[y * w + x]) / 255, 0.85)
                let v = UInt8(min(15, Int((a * 15).rounded())))
                if v == 0 || v == 15 {
                    if run > 0 && runV != v { flush() }
                    runV = v; run += 1
                } else { flush(); nibbles.append(v) }
            } }
            flush()
            if nibbles.count % 2 == 1 { nibbles.append(0) }
            for k in stride(from: 0, to: nibbles.count, by: 2) { data.append(nibbles[k] << 4 | nibbles[k + 1]) }
        }
        let q = Int((advance * 4).rounded())
        precondition(q < 256 && gw < 256 && gh < 256)
        glyphRows.append("Glyph{off:\(off),w:\(gw),h:\(gh),x:\(bx),top:\(top),adv:\(q)}")
    }
    // Kerning for adjacent pairs in the strings this face draws.
    var kern = [(Int, Int, Int)]()
    var seen = Set<String>()
    for s in spec.strings {
        let a = Array(s)
        for k in 0..<max(0, a.count - 1) {
            let pair = String([a[k], a[k + 1]])
            if seen.contains(pair) { continue }
            seen.insert(pair)
            let d = lineWidth(f, pair) - lineWidth(f, String(a[k])) - lineWidth(f, String(a[k + 1]))
            let q = Int((d * 4).rounded())
            if q != 0 { kern.append((Int(map[Int(a[k].asciiValue!) - 32]), Int(map[Int(a[k + 1].asciiValue!) - 32]), q)) }
        }
    }
    kern.sort { ($0.0, $0.1) < ($1.0, $1.1) }
    let ascent = Int(ceil(CTFontGetAscent(f))), descent = Int(ceil(CTFontGetDescent(f)))
    out += "\n// \(spec.file) weight \(Int(spec.weight)) at \(Int(spec.size)) px: \(chars.count) glyphs, \(data.count) bytes\n"
    out += "pub static \(spec.name): Font = Font { ascent: \(ascent), descent: \(descent),\n"
    out += " map: &\(map),\n glyphs: &[\(glyphRows.joined(separator: ","))],\n"
    out += " kern: &[\(kern.map { "(\($0.0),\($0.1),\($0.2))" }.joined(separator: ","))],\n"
    out += " data: &["
    for (k, b) in data.enumerated() { out += (k % 40 == 0 ? "\n  " : "") + "\(b)," }
    out += "\n ] };\n"
    total += data.count + glyphRows.count * 8 + 96 + kern.count * 3
    FileHandle.standardError.write("\(spec.name): \(chars.count) glyphs, \(data.count) bytes data, \(kern.count) kern\n".data(using: .utf8)!)
}
FileHandle.standardError.write("total ~\(total) bytes\n".data(using: .utf8)!)
print(out, terminator: "")
