//! Defines the interned tag and attribute names that Ladybird's tree builder
//! reads as `ladybird_*_tag_name_*` and `ladybird_html_attribute_name_*`.
//! In Ladybird these come from C++ (LibWeb's TagNames and AttributeNames);
//! here they are statics that `names::register` fills from the same headers
//! when the browser starts. Names short enough to fit in a pointer are
//! stored inline by AK and need no static, exactly as Ladybird's own build
//! script decides.
use std::env;
use std::fmt::Write;
use std::fs;
use std::path::PathBuf;

fn names(source: &str, macro_name: &str) -> Vec<(String, String)> {
    let needle = format!("{macro_name}(");
    source
        .lines()
        .filter_map(|line| {
            let rest = &line[line.find(&needle)? + needle.len()..];
            let comma = rest.find(',')?;
            let identifier = rest[..comma].trim().to_string();
            let rest = &rest[comma + 1..];
            let rest = &rest[rest.find('"')? + 1..];
            Some((identifier, rest[..rest.find('"')?].to_string()))
        })
        .collect()
}

fn main() {
    if env::var_os("CARGO_FEATURE_WEBM").is_some() {
        println!("cargo:rerun-if-changed=src/webm.c");
        println!("cargo:rerun-if-env-changed=VIOLET_FFMPEG");
        println!("cargo:rerun-if-env-changed=VIOLET_MUSL_INCLUDE");
        let prefix = PathBuf::from(env::var_os("VIOLET_FFMPEG").expect("FFmpeg prefix"));
        let mut shim = cc::Build::new();
        shim.file("src/webm.c").include(prefix.join("include"));
        if let Some(include) = env::var_os("VIOLET_MUSL_INCLUDE") {
            shim.flag("-isystem").flag(PathBuf::from(include).to_str().unwrap());
        }
        shim.compile("violet_webm");
        println!("cargo:rustc-link-search=native={}", prefix.join("lib").display());
        for lib in ["avformat", "avcodec", "swscale", "swresample", "avutil"] {
            println!("cargo:rerun-if-changed={}", prefix.join(format!("lib/lib{lib}.a")).display());
            println!("cargo:rustc-link-lib=static={lib}");
        }
    }
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let web = manifest.join("../../../build/ladybird/Libraries/LibWeb");
    let pointer = env::var("CARGO_CFG_TARGET_POINTER_WIDTH").unwrap().parse::<usize>().unwrap() / 8;
    let lists = [
        ("HTML/TagNames.h", "__ENUMERATE_HTML_TAG", "html_tag"),
        ("HTML/AttributeNames.h", "__ENUMERATE_HTML_ATTRIBUTE", "html_attribute"),
        ("SVG/TagNames.h", "__ENUMERATE_SVG_TAG", "svg_tag"),
        ("MathML/TagNames.h", "__ENUMERATE_MATHML_TAG", "mathml_tag"),
    ];
    let mut statics = String::new();
    let mut register = String::from("pub fn register(intern: &mut dyn FnMut(&str) -> usize) {\n    unsafe {\n");
    for (header, macro_name, prefix) in lists {
        let path = web.join(header);
        println!("cargo:rerun-if-changed={}", path.display());
        let text = fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e} (run tools/fetch_ladybird.py)", path.display()));
        for (identifier, name) in names(&text, macro_name) {
            if name.len() < pointer && name.is_ascii() {
                continue;
            }
            let symbol = format!("ladybird_{prefix}_name_{identifier}");
            writeln!(statics, "#[unsafe(no_mangle)]\npub static mut {symbol}: usize = 0;").unwrap();
            writeln!(register, "        {symbol} = intern({name:?});").unwrap();
        }
    }
    register.push_str("    }\n}\n");
    let out = PathBuf::from(env::var("OUT_DIR").unwrap()).join("names.rs");
    fs::write(out, format!("// Generated by build.rs.\n{statics}\n{register}")).unwrap();
    let head = manifest.join("../../../build/ladybird/.git/HEAD");
    println!("cargo:rerun-if-changed={}", head.display());
    let commit = fs::read_to_string(&head).unwrap_or_default();
    println!("cargo:rustc-env=LADYBIRD_COMMIT={}", commit.trim().get(..12).unwrap_or("unknown"));
    println!("cargo:rerun-if-changed=build.rs");
}
