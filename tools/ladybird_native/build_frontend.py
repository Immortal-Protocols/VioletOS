"""Cross-build a static AArch64 LibJS compiler for the native runtime bootstrap.

Pass a full checkout of the Ladybird revision in tools/fetch_ladybird.py.
Set RUSTC and CARGO to the pinned toolchain with aarch64-unknown-linux-musl
installed. CC_aarch64_unknown_linux_musl must point to an AArch64 assembler
driver (e.g. clang with CFLAGS_aarch64_unknown_linux_musl=--target=aarch64-linux-musl).
The upstream test host supports parsing and compiling standalone, without LibGC
or ICU. This executable does not run the generated bytecode.
"""

import argparse
import json
import os
from pathlib import Path
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from build_initfs import lld_for


ROOT = Path(__file__).resolve().parents[2]
TARGET = "aarch64-unknown-linux-musl"


def build(source, output):
    rustc = os.environ.get("RUSTC", "rustc")
    cargo = os.environ.get("CARGO", "cargo")
    target_dir = output.parent / "cargo-target"
    sysroot = Path(subprocess.check_output([rustc, "--print", "sysroot"], text=True).strip())
    version = subprocess.check_output([rustc, "-vV"], text=True)
    host = next(line.split()[1] for line in version.splitlines() if line.startswith("host:"))
    lld = lld_for(sysroot, host)
    env = dict(os.environ, CARGO_TARGET_DIR=str(target_dir))
    command = [
        cargo, "rustc", "--manifest-path", str(source / "Cargo.toml"),
        "-p", "libjs_rust", "--target", TARGET, "--release", "--locked",
        "--no-default-features", "--lib", "--message-format", "json-render-diagnostics",
        "--", "--cfg", "test",
    ]
    build_output = subprocess.run(command, env=env, check=True, text=True, stdout=subprocess.PIPE)
    crates = {}
    for line in build_output.stdout.splitlines():
        event = json.loads(line)
        if event.get("reason") == "compiler-artifact":
            for name in event["filenames"]:
                path = Path(name)
                if TARGET in path.parts and path.suffix == ".rlib":
                    crates[event["target"]["name"]] = path

    subprocess.run([
        rustc, "--edition=2024", str(Path(__file__).with_name("compile_js.rs")), "--target", TARGET,
        "-C", f"linker={lld}", "-C", "linker-flavor=ld.lld", "-C", "relocation-model=static",
        "-C", "panic=abort", "-C", "opt-level=2", "-C", "strip=symbols",
        "-L", f"dependency={target_dir / TARGET / 'release/deps'}",
        "-L", f"dependency={target_dir / 'release/deps'}",
        "--extern", f"ak={crates['ak']}", "--extern", f"libjs_rust={crates['libjs_rust']}",
        "-o", str(output),
    ], env=env, check=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--output", type=Path, default=ROOT / "build/ladybird-native/compile-js")
    args = parser.parse_args()
    build(args.source.resolve(), args.output.resolve())
