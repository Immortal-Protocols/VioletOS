"""Camera sensor register tables for the handset, from Motorola's ellis kernel.

The sequences that start the XT2163DL's image sensors are register tables in
Motorola's GPL kernel source. They are not copied into this repository: the
build downloads the pinned file once, checks its SHA-256 and turns the tables
the Camera service uses into a Rust module. Without the download (offline, or
a changed file) the module is empty and Camera reports that it has no tables.
"""
import hashlib
import re
import sys
import urllib.request
from pathlib import Path

COMMIT = "fbd7d0d5c865e48fcd7e3e7483d1e1c0d34c789d"  # android-12-release-s3rhs32.20-42-10-4-11
BASE = f"https://raw.githubusercontent.com/MotorolaMobilityLLC/kernel-mtk/{COMMIT}/"
SOURCES = {
    "hi1336": (
        "drivers/misc/mediatek/imgsensor/src/common/v1/mot_ellis_hi1336_mipi_raw/mot_ellis_hi1336mipiraw_Setting.h",
        "44abc23916f58afa683e4f8f39713d92ab5627ae977308a1a3a5bf752e5d2933",
        {
            "HI1336_INIT": "addr_data_pair_init_mot_ellis_hi1336",
            "HI1336_SLIM": "addr_data_pair_slim_video_mot_ellis_hi1336",
        },
    ),
}


def fetch(path, digest, downloads):
    local = downloads / Path(path).name
    if not local.exists() or hashlib.sha256(local.read_bytes()).hexdigest() != digest:
        downloads.mkdir(parents=True, exist_ok=True)
        try:
            with urllib.request.urlopen(BASE + path, timeout=30) as response:
                data = response.read()
        except OSError as error:
            print(f"sensor tables: download failed ({error})", file=sys.stderr)
            return None
        if hashlib.sha256(data).hexdigest() != digest:
            print(f"sensor tables: {path} does not match its pinned hash", file=sys.stderr)
            return None
        local.write_bytes(data)
    return local.read_text()


def table(source, name):
    match = re.search(r"\b" + re.escape(name) + r"\[\]\s*=\s*\{(.*?)\};", source, re.S)
    if not match:
        raise ValueError(f"no table {name}")
    body = re.sub(r"/\*.*?\*/|//[^\n]*", "", match[1], flags=re.S)
    words = [int(w, 16) for w in re.findall(r"0x[0-9a-fA-F]+", body)]
    if len(words) % 2:
        raise ValueError(f"{name} has an odd number of words")
    return list(zip(words[::2], words[1::2]))


def generate(out, downloads):
    lines = ["// Generated by tools/sensor_tables.py from Motorola's kernel; not for the repository."]
    present = True
    for _, (path, digest, tables) in SOURCES.items():
        source = fetch(path, digest, downloads)
        for rust, c in tables.items():
            pairs = table(source, c) if source else []
            present &= bool(pairs)
            lines.append(f"pub const {rust}: &[(u16, u16)] = &[")
            lines += [f"    (0x{a:04x}, 0x{v:04x})," for a, v in pairs]
            lines.append("];")
    lines.append(f"pub const PRESENT: bool = {'true' if present else 'false'};")
    out.write_text("\n".join(lines) + "\n")
    return present


if __name__ == "__main__":
    generate(Path(sys.argv[1]), Path(sys.argv[2]))
