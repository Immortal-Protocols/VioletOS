"""The handset's operating points and idle states, from the factory device tree.

    python3 tools/power_tables.py FACTORY.dts > targets/moto-g-pure/power_tables.rs

FACTORY.dts is the phone's own device tree as text: an image build leaves it
at build/sel4/moto/upstream/src/plat/ellis/factory-base.dts (kernel/sel4/
build.py decompiles it from the stock boot image). The output is checked in,
so builds and tests need no stock image; rerun this after a firmware change
and commit what differs. `make test-unit` checks the table that is checked
in (targets/moto-g-pure/test_power_tables.rs) and this parser
(tools/test_power_tables.py).

Only what the tree states is emitted: frequency and supply voltage per point
for each CPU cluster, and each idle state's PSCI parameter and latencies.
Not emitted: the table for the bus between the clusters (cci_opp), because
four of its sixteen frequencies in the factory tree read a tenth of what
their neighbours imply (76.3 to 87.8 MHz between 724 and 917 MHz), so it
cannot be trusted as written; and thermal trip points, which the tree does
not have (its thermal nodes name a controller and four thermistor channels,
nothing more).
"""
import re
import sys


def cells(text):
    """The 32-bit cells of a property value as dtc prints it: <...> or, when
    the bytes happen to be printable, strings."""
    text = text.strip()
    if text.startswith("<"):
        return [int(c, 0) for c in text.strip("<>").split()]
    if text.startswith("["):
        raw = bytes(int(b, 16) for b in text.strip("[]").split())
    else:
        raw = b""
        for part in re.findall(r'"((?:[^"\\]|\\.)*)"', text):
            raw += part.encode("latin-1").decode("unicode_escape").encode("latin-1") + b"\0"
    if len(raw) % 4:
        raise ValueError(f"not whole cells: {text!r}")
    return [int.from_bytes(raw[i:i + 4], "big") for i in range(0, len(raw), 4)]


def node(source, label):
    """The body of the node `label: name { ... }`."""
    start = re.search(rf"\b{re.escape(label)}:\s*[\w,@-]+\s*\{{", source)
    if not start:
        raise ValueError(f"no node labelled {label}")
    depth, at = 1, start.end()
    while depth:
        brace = re.compile(r"[{}]").search(source, at)
        if not brace:
            raise ValueError(f"unterminated node {label}")
        depth += 1 if brace.group() == "{" else -1
        at = brace.end()
    return source[start.end():at - 1]


def prop(body, name):
    found = re.search(rf"(?<![\w,-]){re.escape(name)}\s*=\s*([^;]+);", body)
    if not found:
        raise ValueError(f"no property {name}")
    return cells(found.group(1))


def opps(source, label):
    """[(kHz, microvolts)], slowest first."""
    points = []
    for body in re.findall(r"\bopp\d+\s*\{(.*?)\}", node(source, label), re.S):
        hz = prop(body, "opp-hz")
        if len(hz) != 2:
            raise ValueError("opp-hz is not a 64-bit value")
        points.append((((hz[0] << 32) | hz[1]) // 1000, prop(body, "opp-microvolt")[0]))
    points.sort()
    if not points or any(a[0] == b[0] or a[1] > b[1] for a, b in zip(points, points[1:])):
        raise ValueError(f"{label}: points do not rise in frequency and voltage")
    return points


IDLE = ["STANDBY", "MCDI_CPU", "MCDI_CLUSTER", "SODI", "SODI3", "DPIDLE", "SUSPEND"]


def idle_states(source):
    states = []
    for label in IDLE:
        body = node(source, label)
        states.append((label, prop(body, "arm,psci-suspend-param")[0], prop(body, "entry-latency-us")[0],
                       prop(body, "exit-latency-us")[0], prop(body, "min-residency-us")[0]))
    return states


def render(source):
    out = ["// Generated by tools/power_tables.py from the factory device tree; do not edit.",
           "// Data only: nothing on the handset applies these yet (targets/moto-g-pure/power.rs).",
           "use super::Opp;", ""]
    for name, label, what in [("CLUSTER0_OPPS", "cluster0_opp", "CPUs 0-3 (the cores VioletOS runs on)"),
                              ("CLUSTER1_OPPS", "cluster1_opp", "CPUs 4-7")]:
        points = opps(source, label)
        out.append(f"/// {what}: kHz and microvolts, slowest first.")
        out.append(f"pub static {name}: [Opp; {len(points)}] = [")
        out += [f"    Opp {{ khz: {khz}, uv: {uv} }}," for khz, uv in points]
        out += ["];", ""]
    states = idle_states(source)
    out += ["/// A CPU idle state the firmware offers through PSCI CPU_SUSPEND.",
            "pub struct IdleState {", "    pub name: &'static str,", "    pub psci_param: u32,",
            "    pub entry_us: u32,", "    pub exit_us: u32,", "    pub min_residency_us: u32,", "}",
            "/// Shallowest first.", f"pub static IDLE_STATES: [IdleState; {len(states)}] = ["]
    out += [f'    IdleState {{ name: "{n}", psci_param: {p:#x}, entry_us: {e}, exit_us: {x}, min_residency_us: {r} }},'
            for n, p, e, x, r in states]
    out += ["];", ""]
    return "\n".join(out)


if __name__ == "__main__":
    sys.stdout.write(render(open(sys.argv[1]).read()))
