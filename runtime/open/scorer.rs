//! Violet Shield's on-device scorer: what the phone concludes about an app
//! by itself, with no companion linked (docs/violet-shield-poc.md).
//!
//! For every process it keeps 16 recent security events the Open Runtime
//! recorded (shield.rs), turns them into 24 small integers, and runs a
//! 24 -> 12 -> 4 integer network over them. When a window is full, plain
//! opens of the app's own files go first, so an app cannot push the events
//! that matter out with filler; and a few facts (`Facts`) are kept for as
//! long as the process is watched, whatever leaves the window. The weights and both thresholds
//! are generated by tools/shield-trainer/train_tiny.py into scorer_model.rs
//! and checked in; tools/shield-trainer/tiny.py is the reference this file
//! must match bit for bit (`make test-unit` replays its fixtures).
//!
//! The network was trained on synthetic windows only, so its word alone
//! never contains an app. `decide` asks for a second, deterministic sign
//! (`corroborated`), and the program must be one the phone may contain
//! (`ShieldPolicy::eligible`). Otherwise the most it does is warn.
//!
//! No floating point, no seL4 calls: the host tests run exactly this code.
use super::policy::AppId;
use super::scorer_model as model;
use super::shield::{self, EventKind, ShieldPolicy, Subject, TelemetryEvent};
use alloc::vec::Vec;

pub const FEATURE_VERSION: u32 = 1;
pub const F: usize = 24;
/// Events a window keeps.
pub const WINDOW: usize = 16;
/// Processes scored at once; the one idle longest makes room.
pub const MAX_WINDOWS: usize = 12;
/// Windows scored in one 100 ms turn.
pub const PER_TICK: usize = 2;
/// How long the scorer freezes an app that tried to overwrite code.
pub const FREEZE_SECS: u32 = 30;
const _: () = assert!(model::FEATURE_VERSION == FEATURE_VERSION && model::F == F);

const BIT_IP: u8 = 1;
const BIT_ODD_PORT: u8 = 2;
const BIT_SYSTEM: u8 = 4;
const BIT_TMP_EXEC: u8 = 8;

// Feature indices (tiny.py FEATURES).
pub const F_BG: usize = 0;
pub const F_NEW: usize = 1;
pub const F_DEV: usize = 2;
pub const F_IDLE: usize = 3;
pub const F_EVENTS: usize = 4;
pub const F_XREAD: usize = 5;
pub const F_XWRITE: usize = 6;
pub const F_SYSW: usize = 7;
pub const F_WX: usize = 8;
pub const F_EXEC: usize = 9;
pub const F_TMPEXEC: usize = 10;
pub const F_CONN: usize = 11;
pub const F_DEST: usize = 12;
pub const F_IP: usize = 13;
pub const F_ODD: usize = 14;
pub const F_TX: usize = 15;
pub const F_TX_AFTER: usize = 16;
pub const F_DIGITS: usize = 17;
pub const F_HYPHENS: usize = 18;
pub const F_LABELS: usize = 19;
pub const F_REPEAT: usize = 20;
pub const F_SMALL: usize = 21;
pub const F_UDP: usize = 22;
pub const F_BGTX: usize = 23;

const EXEC: u8 = EventKind::Exec as u8;
const OPEN_R: u8 = EventKind::OpenRead as u8;
const OPEN_W: u8 = EventKind::OpenWrite as u8;
const CONN: u8 = EventKind::NetConnect as u8;
const TX: u8 = EventKind::NetTxSummary as u8;
const WX: u8 = EventKind::MemoryWx as u8;

/// One event as a window keeps it (16 bytes).
#[derive(Clone, Copy, Default, Debug, PartialEq, Eq)]
pub struct Ev {
    pub kind: u8,
    pub flags: u8,
    bits: u8,
    digits: u8,
    hyphens: u8,
    labels: u8,
    dest: u32,
    bytes: u32,
}

fn fnv(mut h: u32, b: u8) -> u32 {
    h ^= u32::from(b);
    h.wrapping_mul(0x0100_0193)
}

fn under(path: &str, dir: &str) -> bool {
    path.strip_prefix(dir).map_or(false, |rest| rest.is_empty() || rest.starts_with('/'))
}

impl Ev {
    /// A connection or a send to `host:port` (the first 40 bytes of the name count).
    pub fn net(kind: u8, flags: u8, host: &[u8], port: u16, bytes: u32) -> Ev {
        let host = &host[..host.len().min(40)];
        let mut e = Ev { kind, flags, bytes, labels: 1, ..Ev::default() };
        let mut h = 0x811c_9dc5;
        let mut ip = !host.is_empty();
        for b in host {
            let c = b.to_ascii_lowercase();
            h = fnv(h, c);
            match c {
                b'0'..=b'9' => e.digits = (e.digits + 1).min(15),
                b'.' => e.labels = (e.labels + 1).min(15),
                _ => {
                    ip = false;
                    if c == b'-' {
                        e.hyphens = (e.hyphens + 1).min(15);
                    }
                }
            }
        }
        e.dest = fnv(fnv(h, port as u8), (port >> 8) as u8);
        if ip {
            e.bits |= BIT_IP;
        }
        if port != 80 && port != 443 {
            e.bits |= BIT_ODD_PORT;
        }
        e
    }

    /// An open of the app's own files that says nothing by itself: the first
    /// to leave a full window.
    fn plain(&self) -> bool {
        matches!(self.kind, OPEN_R | OPEN_W) && self.flags & shield::FLAG_CROSS_APP == 0 && self.bits & BIT_SYSTEM == 0
    }

    /// A read of another app's files.
    fn crossing(&self) -> bool {
        self.kind == OPEN_R && self.flags & shield::FLAG_CROSS_APP != 0
    }

    /// A program start, file open or W+X map; `text` is the path or command
    /// line (its first 40 bytes count: that is what the phone records).
    pub fn local(kind: u8, flags: u8, text: &str) -> Ev {
        let mut cut = text.len().min(40);
        while !text.is_char_boundary(cut) {
            cut -= 1;
        }
        let text = &text[..cut];
        let mut e = Ev { kind, flags, ..Ev::default() };
        if kind == OPEN_W && (under(text, "/bin") || under(text, "/lib") || flags & shield::FLAG_CROSS_APP != 0 && text.starts_with("/apps/")) {
            e.bits |= BIT_SYSTEM;
        }
        // A program or script under /tmp or /data, anywhere on the command line.
        if kind == EXEC {
            let t = text.as_bytes();
            let starts = |at: usize, p: &[u8]| t.len() >= at + p.len() && &t[at..at + p.len()] == p;
            if (0..t.len()).any(|n| (n == 0 || t[n - 1] == b' ') && (starts(n, b"/tmp/") || starts(n, b"/data/"))) {
                e.bits |= BIT_TMP_EXEC;
            }
        }
        e
    }

    /// None for the kinds a window ignores.
    pub fn from_event(ev: &TelemetryEvent) -> Option<Ev> {
        match ev.kind {
            CONN => Some(Ev::net(CONN, ev.flags, ev.detail_str().as_bytes(), ev.port, 0)),
            TX => Some(Ev::net(TX, ev.flags, ev.detail_str().as_bytes(), ev.port, ev.aux_u32)),
            EXEC | OPEN_R | OPEN_W | WX => Some(Ev::local(ev.kind, ev.flags, ev.detail_str())),
            _ => None,
        }
    }
}

/// What is remembered about a process whatever leaves its window: the
/// deterministic signs `corroborated` asks for.
#[derive(Clone, Copy, Default, Debug, PartialEq, Eq)]
pub struct Facts {
    /// It read another app's files.
    pub crossed: bool,
    /// It tried to write another app's program or a system file.
    pub system_write: bool,
    /// Bytes sent since it first read another app's files.
    pub tx_after: u32,
}

/// The recent events of one process.
#[derive(Clone, Debug)]
pub struct Window {
    pub pid: u32,
    events: [Ev; WINDOW],
    len: u8,
    flags: u8,
    idle_s: u32,
    dirty: bool,
    /// A read of another app's files has left the window: sends still in it
    /// count as sent after one.
    carried: bool,
    pub facts: Facts,
    /// The strongest action already reported for this window (NONE..FREEZE),
    /// and the Shield mode it was reported under.
    acted: u8,
    acted_mode: u8,
    used: u64,
}

fn bits(v: u32) -> u8 {
    (32 - v.leading_zeros()) as u8
}

impl Window {
    pub fn new(pid: u32) -> Window {
        Window { pid, events: [Ev::default(); WINDOW], len: 0, flags: 0, idle_s: 0, dirty: false, carried: false, facts: Facts::default(), acted: NONE, acted_mode: 0, used: 0 }
    }

    /// Changed since it was last scored.
    pub fn pending(&self) -> bool {
        self.dirty
    }

    /// Add an event; a send to the destination of the send before it adds to
    /// that one. A full window gives up its oldest plain open; if it holds
    /// none, a new plain open is not kept, and anything else replaces the
    /// oldest event.
    pub fn add(&mut self, ev: Ev, idle_s: u32) {
        self.flags = ev.flags;
        self.idle_s = idle_s;
        self.dirty = true;
        if ev.crossing() {
            self.facts.crossed = true;
        }
        if ev.kind == OPEN_W && ev.bits & BIT_SYSTEM != 0 {
            self.facts.system_write = true;
        }
        if ev.kind == TX && self.facts.crossed {
            self.facts.tx_after = self.facts.tx_after.saturating_add(ev.bytes);
        }
        let mut n = self.len as usize;
        if ev.kind == TX && n > 0 && self.events[n - 1].kind == TX && self.events[n - 1].dest == ev.dest {
            let last = &mut self.events[n - 1];
            last.bytes = last.bytes.saturating_add(ev.bytes);
            last.flags = ev.flags;
            return;
        }
        if n == WINDOW {
            let out = match self.events.iter().position(Ev::plain) {
                Some(at) => at,
                None if ev.plain() => return,
                None => 0,
            };
            self.carried |= self.events[out].crossing();
            self.events.copy_within(out + 1.., out);
            n -= 1;
        } else {
            self.len += 1;
        }
        self.events[n] = ev;
    }

    /// After the app was contained for what it did: the signs `corroborated`
    /// asks for start over, so it is contained again only for something it
    /// does afterwards (another 64 KiB sent, another write to a program).
    /// That it read another app's files stays true.
    fn spend(&mut self) {
        self.facts.system_write = false;
        self.facts.tx_after = 0;
        self.acted = WARN;
    }

    pub fn features(&self) -> [u8; F] {
        let mut f = [0u8; F];
        let ev = &self.events[..self.len as usize];
        f[F_BG] = (self.flags & shield::FLAG_BACKGROUND != 0) as u8;
        f[F_NEW] = (self.flags & shield::FLAG_NEW_HASH != 0) as u8;
        f[F_DEV] = (self.flags & shield::FLAG_DEV_PUSH != 0) as u8;
        f[F_IDLE] = bits(self.idle_s).min(15);
        f[F_EVENTS] = ev.len() as u8;
        let (mut tx, mut tx_after, mut tx_bg) = (0u32, 0u32, 0u32);
        let mut crossed = self.carried;
        for (n, e) in ev.iter().enumerate() {
            let cross = (e.flags & shield::FLAG_CROSS_APP != 0) as u8;
            match e.kind {
                OPEN_R if cross != 0 => {
                    f[F_XREAD] += 1;
                    crossed = true;
                }
                OPEN_W => {
                    f[F_XWRITE] += cross;
                    f[F_SYSW] += (e.bits & BIT_SYSTEM != 0) as u8;
                }
                WX => f[F_WX] += 1,
                EXEC => {
                    f[F_EXEC] += 1;
                    f[F_TMPEXEC] += (e.bits & BIT_TMP_EXEC != 0) as u8;
                }
                CONN => {
                    f[F_CONN] += 1;
                    f[F_IP] += (e.bits & BIT_IP != 0) as u8;
                    f[F_ODD] += (e.bits & BIT_ODD_PORT != 0) as u8;
                    f[F_DIGITS] = f[F_DIGITS].max(e.digits);
                    f[F_HYPHENS] = f[F_HYPHENS].max(e.hyphens);
                    f[F_LABELS] = f[F_LABELS].max(e.labels);
                    let same = ev[..=n].iter().filter(|o| o.kind == CONN && o.dest == e.dest).count() as u8;
                    f[F_REPEAT] = f[F_REPEAT].max(same);
                    f[F_UDP] |= (e.flags & shield::FLAG_UDP != 0) as u8;
                }
                TX => {
                    tx = tx.saturating_add(e.bytes);
                    if crossed {
                        tx_after = tx_after.saturating_add(e.bytes);
                    }
                    if e.flags & shield::FLAG_BACKGROUND != 0 {
                        tx_bg = tx_bg.saturating_add(e.bytes);
                    }
                    f[F_SMALL] += (e.bytes < 512) as u8;
                }
                _ => {}
            }
            if matches!(e.kind, CONN | TX) && !ev[..n].iter().any(|o| matches!(o.kind, CONN | TX) && o.dest == e.dest) {
                f[F_DEST] += 1;
            }
        }
        f[F_TX] = bits(tx);
        f[F_TX_AFTER] = bits(tx_after);
        f[F_BGTX] = bits(tx_bg);
        for n in [F_XREAD, F_XWRITE, F_SYSW, F_WX, F_EXEC, F_TMPEXEC, F_CONN, F_DEST, F_IP, F_ODD, F_REPEAT, F_SMALL] {
            f[n] = f[n].min(15);
        }
        f
    }
}

/// The network: four logits, in the order of schema.VERDICTS
/// (benign, suspicious, exfil_or_c2, exploit_or_persistence).
pub fn logits(f: &[u8; F]) -> [i32; 4] {
    let mut hidden = [0i32; model::H];
    for (j, h) in hidden.iter_mut().enumerate() {
        let mut acc = model::B1[j];
        for k in 0..F {
            acc += i32::from(model::W1[j][k]) * i32::from(f[k]);
        }
        *h = (acc.max(0) >> model::SHIFT1).min(127);
    }
    let mut out = model::B2;
    for (c, o) in out.iter_mut().enumerate() {
        for j in 0..model::H {
            *o += i32::from(model::W2[c][j]) * hidden[j];
        }
    }
    out
}

/// Index of the largest logit (the first one on a tie).
pub fn verdict(l: &[i32; 4]) -> u8 {
    let mut best = 0;
    for n in 1..4 {
        if l[n] > l[best] {
            best = n;
        }
    }
    best as u8
}

/// How far the two malicious verdicts are ahead of benign and suspicious.
/// "Suspicious" alone calls for nothing on the phone.
pub fn margin(l: &[i32; 4]) -> i32 {
    l[2].max(l[3]) - l[0].max(l[1])
}

/// A second, deterministic sign: a write to another app's program or a
/// system file, or 64 KiB or more sent after reading another app's data by
/// an app that is now in the background. Taken from the facts kept about the
/// process, not from the window, so filling the window does not remove it
/// (and whatever the window shows of either, the facts hold too).
pub fn corroborated(f: &[u8; F], facts: &Facts) -> bool {
    facts.system_write || f[F_BG] == 1 && facts.tx_after >= 64 * 1024
}

pub const NONE: u8 = 0;
pub const WARN: u8 = 1;
pub const QUARANTINE: u8 = 2;
pub const FREEZE: u8 = 3;

/// What a score calls for. `eligible`: the phone may contain this program.
pub fn decide(l: &[i32; 4], f: &[u8; F], facts: &Facts, eligible: bool) -> u8 {
    if margin(l) < model::T_WARN {
        NONE
    } else if !eligible || margin(l) < model::T_CONTAIN || !corroborated(f, facts) {
        WARN
    } else if verdict(l) == 3 && facts.system_write {
        FREEZE
    } else {
        QUARANTINE
    }
}

/// What the scorer just did about a process.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Local {
    pub pid: u32,
    /// WARN, QUARANTINE or FREEZE: what the score called for.
    pub action: u8,
    /// False when it was only reported (monitoring).
    pub enforced: bool,
    pub verdict: u8,
    pub margin: i32,
}

/// What the scorer acts through. In the Sentinel (system/sentinel/scoring.rs)
/// it is the reply to the Open Runtime, which carries the result out; in the
/// host replay it is the policy itself.
pub trait Enforcer {
    /// The Shield's mode (`shield::Mode as u8`).
    fn mode(&self) -> u8;
    fn eligible(&self, who: &Subject) -> bool;
    /// Contain `who` if the mode and its role allow it; true if contained.
    fn trip(&mut self, now_ns: u64, who: &Subject, shield_id: u32) -> bool;
    fn emit(&mut self, ev: TelemetryEvent);
}

impl Enforcer for ShieldPolicy {
    fn mode(&self) -> u8 {
        self.mode as u8
    }
    fn eligible(&self, who: &Subject) -> bool {
        ShieldPolicy::eligible(self, who)
    }
    fn trip(&mut self, now_ns: u64, who: &Subject, shield_id: u32) -> bool {
        ShieldPolicy::trip(self, now_ns, who, shield_id)
    }
    fn emit(&mut self, ev: TelemetryEvent) {
        self.ring.emit(ev);
    }
}

/// "quarantine v=2 m=17 model=55fedf7e": the LocalScore record's text.
/// (Written out by hand: the Sentinel carries no formatting code.)
pub fn score_text(action: u8, verdict: u8, margin: i32) -> alloc::string::String {
    let mut s = alloc::string::String::from(["", "warn", "quarantine", "freeze"][(action as usize).min(3)]);
    let dec = |s: &mut alloc::string::String, v: i64| {
        if v < 0 {
            s.push('-');
        }
        let (mut digits, mut n, mut v) = ([0u8; 12], 0, v.unsigned_abs());
        loop {
            digits[n] = b'0' + (v % 10) as u8;
            n += 1;
            v /= 10;
            if v == 0 {
                break;
            }
        }
        while n > 0 {
            n -= 1;
            s.push(digits[n] as char);
        }
    };
    s.push_str(" v=");
    dec(&mut s, i64::from(verdict));
    s.push_str(" m=");
    dec(&mut s, i64::from(margin));
    s.push_str(" model=");
    for shift in (0..8).rev() {
        s.push(b"0123456789abcdef"[(model::MODEL_ID >> (shift * 4)) as usize & 15] as char);
    }
    s
}

pub struct Scorer {
    pub windows: Vec<Window>,
    clock: u64,
    /// Where the next turn starts looking, so every window gets its turn.
    next: usize,
    /// Windows scored since boot, and how many of them warned.
    pub scored: u32,
    pub warned: u32,
}

impl Scorer {
    pub fn new() -> Scorer {
        Scorer { windows: Vec::new(), clock: 0, next: 0, scored: 0, warned: 0 }
    }

    pub fn ingest(&mut self, ev: &TelemetryEvent, idle_s: u32) {
        if ev.kind == EventKind::Exit as u8 {
            self.windows.retain(|w| w.pid != ev.app_id);
            return;
        }
        let Some(e) = Ev::from_event(ev) else { return };
        self.clock += 1;
        let at = match self.windows.iter().position(|w| w.pid == ev.app_id) {
            Some(at) => at,
            None => {
                if self.windows.len() >= MAX_WINDOWS {
                    let oldest = (0..self.windows.len()).min_by_key(|&n| self.windows[n].used).unwrap_or(0);
                    self.windows.remove(oldest);
                }
                self.windows.push(Window::new(ev.app_id));
                self.windows.len() - 1
            }
        };
        self.windows[at].used = self.clock;
        self.windows[at].add(e, idle_s);
    }

    /// One turn: take in the new events, score up to `PER_TICK` windows that
    /// changed (taking turns, so a busy process cannot keep another's window
    /// from being scored), and act through `policy` (which reports instead
    /// when it is monitoring). `subjects` are the running apps. Returns what
    /// was done that the runtime must log, count or (for FREEZE) carry out.
    ///
    /// The same action is not reported twice for a window, with two
    /// exceptions: after the Shield's mode changes it is decided afresh, and
    /// once an app was actually contained the deterministic signs start
    /// over (`spend`), so doing it again after the quarantine ends is a new
    /// offence (30 s, 5 min, until released).
    pub fn step<E: Enforcer>(&mut self, policy: &mut E, events: &[TelemetryEvent], idle_s: u32, now_ns: u64, subjects: &[Subject]) -> Vec<Local> {
        for ev in events {
            self.ingest(ev, idle_s);
        }
        let mut out = Vec::new();
        let count = self.windows.len();
        for _ in 0..PER_TICK {
            let Some(at) = (0..count).map(|k| (self.next + k) % count).find(|&n| self.windows[n].dirty) else { break };
            self.next = (at + 1) % count;
            let w = &mut self.windows[at];
            w.dirty = false;
            let Some(who) = subjects.iter().find(|s| s.app.0 == w.pid) else { continue };
            let f = w.features();
            let l = logits(&f);
            self.scored = self.scored.wrapping_add(1);
            let action = decide(&l, &f, &w.facts, policy.eligible(who));
            if w.acted_mode != policy.mode() {
                w.acted = NONE;
                w.acted_mode = policy.mode();
            }
            if action <= w.acted {
                if action == NONE {
                    w.acted = NONE;
                }
                continue;
            }
            w.acted = action;
            self.warned = self.warned.wrapping_add(1);
            let enforced = action >= QUARANTINE && policy.trip(now_ns, who, shield::ID_SCORER);
            if enforced {
                w.spend();
            }
            let text = score_text(action, verdict(&l), margin(&l));
            let mut ev = TelemetryEvent::new(now_ns, AppId(w.pid), EventKind::LocalScore, who.flags | shield::FLAG_HIGH_PRIORITY, text.as_bytes());
            ev.aux_u32 = model::MODEL_ID;
            policy.emit(ev);
            out.push(Local { pid: w.pid, action, enforced, verdict: verdict(&l), margin: margin(&l) });
        }
        out
    }
}
